/**
 * Embed a pre-built site as the template the editor exports from.
 *
 * Exporting by cloning the live editor page carries the whole editor bundle
 * (a 1.2 MB site exports as 5-6 MB). Instead: build the plain site first,
 * embed it here, then build the editor. Export then injects the config into
 * this slim template.
 *
 * Usage: node scripts/embed-template.mjs [source.html] [target.js] [exportName]
 * Defaults: dist/index.html → src/editor/template.generated.js → SLIM_TEMPLATE
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const [sourceArg, targetArg, exportName = 'SLIM_TEMPLATE'] = process.argv.slice(2)
const source = resolve(sourceArg ?? 'dist/index.html')
const target = resolve(targetArg ?? 'src/editor/template.generated.js')

const html = await readFile(source, 'utf8')
const module = `/**
 * Generated by scripts/embed-template.mjs — do not edit.
 * Source: ${source}
 */
export const ${exportName} = ${JSON.stringify(html)}
`

await writeFile(target, module, 'utf8')
console.log(`[embed-template] ${Math.round(html.length / 1024)} KB → ${target}`)
